//! Low-level keyboard hook and SendInput engine for Windows.

#[cfg(windows)]
pub mod win {
    use crate::config::{SwitchShortcut, WinConfig};
    use rustype_core::telex::{Config as CoreConfig, Telex};
    use std::sync::atomic::AtomicBool;
    use std::sync::Mutex;
    use windows_sys::Win32::Foundation::{LPARAM, LRESULT, WPARAM};
    use windows_sys::Win32::UI::Input::KeyboardAndMouse::*;
    use windows_sys::Win32::UI::WindowsAndMessaging::*;

    #[derive(Clone, Copy)]
    struct SendHHook(HHOOK);
    unsafe impl Send for SendHHook {}

    static HOOK_HANDLE: Mutex<Option<SendHHook>> = Mutex::new(None);
    static ENGINE: Mutex<Option<HookEngine>> = Mutex::new(None);
    pub static RUNNING: AtomicBool = AtomicBool::new(true);

    pub struct HookEngine {
        pub telex: Telex,
        pub config: WinConfig,
        ctrl_down: bool,
        shift_down: bool,
        alt_down: bool,
    }

    impl HookEngine {
        pub fn new(config: WinConfig) -> Self {
            let core_cfg = CoreConfig {
                modern_orthography: config.modern_orthography,
                auto_restore_english: config.auto_restore_english,
                input_method: config.input_method,
                ..Default::default()
            };
            Self {
                telex: Telex::new(core_cfg),
                config,
                ctrl_down: false,
                shift_down: false,
                alt_down: false,
            }
        }

        pub fn reload_config(&mut self, config: WinConfig) {
            self.config = config.clone();
            self.telex.cfg.modern_orthography = config.modern_orthography;
            self.telex.cfg.auto_restore_english = config.auto_restore_english;
            self.telex.cfg.input_method = config.input_method;
        }

        pub fn toggle_enabled(&mut self) -> bool {
            self.config.enabled = !self.config.enabled;
            self.telex.reset();
            self.config.enabled
        }
    }

    /// Low-level keyboard hook callback procedure.
    ///
    /// # Safety
    /// `l_param` must be a valid pointer to a `KBDLLHOOKSTRUCT` as passed by the OS hook subsystem.
    pub unsafe extern "system" fn low_level_keyboard_proc(
        n_code: i32,
        w_param: WPARAM,
        l_param: LPARAM,
    ) -> LRESULT {
        if n_code != HC_ACTION as i32 {
            return CallNextHookEx(std::ptr::null_mut(), n_code, w_param, l_param);
        }

        let kbd = *(l_param as *const KBDLLHOOKSTRUCT);

        // Ignore injected events generated by our own SendInput to prevent recursive loops
        if (kbd.flags & LLKHF_INJECTED) != 0 {
            return CallNextHookEx(std::ptr::null_mut(), n_code, w_param, l_param);
        }

        let msg = w_param as u32;
        let is_down = msg == WM_KEYDOWN || msg == WM_SYSKEYDOWN;
        let _is_up = msg == WM_KEYUP || msg == WM_SYSKEYUP;

        let mut lock = ENGINE.lock().unwrap();
        let Some(engine) = lock.as_mut() else {
            return CallNextHookEx(std::ptr::null_mut(), n_code, w_param, l_param);
        };

        // Track modifiers
        match kbd.vkCode as u16 {
            VK_LCONTROL | VK_RCONTROL | VK_CONTROL => {
                engine.ctrl_down = is_down;
            }
            VK_LSHIFT | VK_RSHIFT | VK_SHIFT => {
                engine.shift_down = is_down;
                if is_down
                    && engine.ctrl_down
                    && engine.config.switch_shortcut == SwitchShortcut::CtrlShift
                {
                    engine.toggle_enabled();
                }
            }
            VK_LMENU | VK_RMENU | VK_MENU => {
                engine.alt_down = is_down;
            }
            _ => {}
        }

        // Check Alt+Z shortcut
        if is_down
            && engine.alt_down
            && kbd.vkCode == b'Z' as u32
            && engine.config.switch_shortcut == SwitchShortcut::AltZ
        {
            engine.toggle_enabled();
            return 1; // Consume key
        }

        // If Vietnamese mode is disabled or holding Ctrl/Alt, bypass to application
        if !engine.config.enabled || engine.ctrl_down || engine.alt_down {
            if is_down && (kbd.vkCode == VK_RETURN as u32 || kbd.vkCode == VK_ESCAPE as u32) {
                engine.telex.reset();
            }
            return CallNextHookEx(std::ptr::null_mut(), n_code, w_param, l_param);
        }

        if is_down {
            // Handle Backspace
            if kbd.vkCode == VK_BACK as u32 {
                let res = engine.telex.backspace();
                if res.handled {
                    send_replacement(res.backspaces, &res.commit);
                    return 1;
                }
                return CallNextHookEx(std::ptr::null_mut(), n_code, w_param, l_param);
            }

            // Convert Virtual Key to character using active keyboard state
            if let Some(ch) = vk_to_char(kbd.vkCode, kbd.scanCode) {
                let res = engine.telex.key(ch);
                if res.handled {
                    send_replacement(res.backspaces, &res.commit);
                    return 1; // Consumed, replacement sent
                }
            } else {
                // Non-character key (arrows, Home, End, Tab, etc.) resets word
                engine.telex.reset();
            }
        }

        CallNextHookEx(std::ptr::null_mut(), n_code, w_param, l_param)
    }

    /// Sends backspaces followed by unicode character commits using Windows SendInput API.
    unsafe fn send_replacement(backspaces: usize, commit: &str) {
        let utf16_chars: Vec<u16> = commit.encode_utf16().collect();
        let total_inputs = (backspaces * 2) + (utf16_chars.len() * 2);
        if total_inputs == 0 {
            return;
        }

        let mut inputs: Vec<INPUT> = Vec::with_capacity(total_inputs);

        // 1. Send Backspaces (Down + Up)
        for _ in 0..backspaces {
            let mut down: INPUT = std::mem::zeroed();
            down.r#type = INPUT_KEYBOARD;
            down.Anonymous.ki.wVk = VK_BACK;
            inputs.push(down);

            let mut up: INPUT = std::mem::zeroed();
            up.r#type = INPUT_KEYBOARD;
            up.Anonymous.ki.wVk = VK_BACK;
            up.Anonymous.ki.dwFlags = KEYEVENTF_KEYUP;
            inputs.push(up);
        }

        // 2. Send Unicode Characters (Down + Up)
        for &u in &utf16_chars {
            let mut down: INPUT = std::mem::zeroed();
            down.r#type = INPUT_KEYBOARD;
            down.Anonymous.ki.dwFlags = KEYEVENTF_UNICODE;
            down.Anonymous.ki.wScan = u;
            inputs.push(down);

            let mut up: INPUT = std::mem::zeroed();
            up.r#type = INPUT_KEYBOARD;
            up.Anonymous.ki.dwFlags = KEYEVENTF_UNICODE | KEYEVENTF_KEYUP;
            up.Anonymous.ki.wScan = u;
            inputs.push(up);
        }

        SendInput(
            inputs.len() as u32,
            inputs.as_ptr(),
            std::mem::size_of::<INPUT>() as i32,
        );
    }

    /// Translates a virtual key code into a unicode character.
    unsafe fn vk_to_char(vk: u32, scan_code: u32) -> Option<char> {
        let mut key_state = [0u8; 256];
        if GetKeyboardState(key_state.as_mut_ptr()) == 0 {
            return None;
        }

        let mut buffer = [0u16; 4];
        let ret = ToUnicode(
            vk,
            scan_code,
            key_state.as_ptr(),
            buffer.as_mut_ptr(),
            buffer.len() as i32,
            0,
        );

        if ret > 0 {
            char::decode_utf16(buffer[0..ret as usize].iter().cloned())
                .next()
                .and_then(|r| r.ok())
        } else {
            None
        }
    }

    /// Installs the low-level keyboard hook.
    pub fn install_hook(config: WinConfig) -> bool {
        unsafe {
            let mut engine_lock = ENGINE.lock().unwrap();
            *engine_lock = Some(HookEngine::new(config));

            let h_instance =
                windows_sys::Win32::System::LibraryLoader::GetModuleHandleW(std::ptr::null());
            let hook =
                SetWindowsHookExW(WH_KEYBOARD_LL, Some(low_level_keyboard_proc), h_instance, 0);

            if !hook.is_null() {
                let mut hook_lock = HOOK_HANDLE.lock().unwrap();
                *hook_lock = Some(SendHHook(hook));
                true
            } else {
                false
            }
        }
    }

    /// Uninstalls the low-level keyboard hook.
    pub fn uninstall_hook() {
        unsafe {
            let mut hook_lock = HOOK_HANDLE.lock().unwrap();
            if let Some(hook) = hook_lock.take() {
                UnhookWindowsHookEx(hook.0);
            }
            let mut engine_lock = ENGINE.lock().unwrap();
            *engine_lock = None;
        }
    }
}
